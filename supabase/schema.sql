-- Banco de dados da Biblioteca On-line
-- Execute este script no SQL Editor do seu projeto Supabase.

create table if not exists public.livros (
    id bigint generated by default as identity primary key,
    titulo text not null,
    autor text not null,
    categoria text not null default 'Ficção',
    preco numeric(10, 2) not null default 0 check (preco >= 0),
    estoque integer not null default 0 check (estoque >= 0),
    emprestados integer not null default 0 check (emprestados >= 0),
    vendidos integer not null default 0 check (vendidos >= 0),
    criado_em timestamptz not null default now()
);

alter table public.livros enable row level security;

-- Políticas para demonstração escolar sem login.
-- ATENÇÃO: qualquer pessoa que tenha a URL e a chave pública do projeto
-- poderá consultar e alterar os registros. Para uso real, implemente login
-- e restrinja estas políticas a usuários autenticados.
drop policy if exists "Acesso publico para consultar livros" on public.livros;
create policy "Acesso publico para consultar livros"
on public.livros for select to anon using (true);

drop policy if exists "Acesso publico para cadastrar livros" on public.livros;
create policy "Acesso publico para cadastrar livros"
on public.livros for insert to anon with check (true);

drop policy if exists "Acesso publico para atualizar livros" on public.livros;
create policy "Acesso publico para atualizar livros"
on public.livros for update to anon using (true) with check (true);

drop policy if exists "Acesso publico para excluir livros" on public.livros;
create policy "Acesso publico para excluir livros"
on public.livros for delete to anon using (true);


-- Permissões SQL para o cliente público do site.
-- As políticas RLS acima continuam controlando quais linhas podem ser acessadas.
grant usage on schema public to anon;
grant select, insert, update, delete on table public.livros to anon;
grant usage, select on sequence public.livros_id_seq to anon;
